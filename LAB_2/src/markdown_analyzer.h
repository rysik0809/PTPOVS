#pragma once

#include <cstddef>
#include <ostream>
#include <string>

/**
 * @brief Агрегированная статистика одного прогона анализа Markdown-файла.
 */
struct AnalysisStats 
{
    std::size_t totalLines = 0;  ///< Всего обработанных строк файла.
    std::size_t headings = 0;  ///< Найдено заголовков.
    std::size_t paragraphs = 0;  ///< Найдено абзацев (склеенные строки).
    std::size_t listItems = 0;  ///< Найдено элементов списков.
    std::size_t foreignLines = 0;  ///< Строк с маркерами HTML/AsciiDoc.
};

/**
 * @brief Проверяет, содержит ли строка маркеры чужой разметки.
 *
 * Ищет признаки HTML-тега (<tag>) и AsciiDoc (= H, ----, ....).
 * Используется для диагностического предупреждения, а не для решения
 * «валидна/невалидна» — пустая строка здесь вернёт false.
 *
 * @param line Строка без завершающего '\n' и '\r'.
 * @return true, если обнаружен маркер HTML или AsciiDoc.
 *
 * @note Не модифицирует и не копирует строку; сложность O(длины строки).
 */
bool isForeignMarkup(const std::string& line);

/**
 * @brief Проверяет, является ли строка допустимой в Markdown.
 *
 * В отличие от isForeignMarkup, пустая строка и строка из пробелов
 * считаются валидными (разделители абзацев в Markdown). Возвращает
 * !isForeignMarkup(line) для непустых строк.
 *
 * @param line Строка без завершающего '\n'.
 * @return true, если строка не содержит маркеров чужой разметки.
 *
 * @note Публичная обёртка; внутри анализатора используется
 *       string_view-версия, чтобы не копировать каждую строк.
 */
bool isValidMarkdownLine(const std::string& line);

/**
 * @brief Анализирует Markdown-файл потоково и пишет элементы в out.
 *
 * Читает файл блоками фиксированного размера, разбирает строки внутри
 * блока и сразу пишет найденные заголовки, абзацы и элементы списков
 * в out. Возвращает агрегированные счётчики; сами элементы в память
 * не складываются.
 *
 * @param filename Путь к входному файлу. Не должен быть пустым.
 * @param out  Поток для записи результатов. Должен быть открыт
 *                     вызывающей стороной; функция его не закрывает.
 * @param blockSize Размер блока чтения в байтах. 0 трактуется как
 *                      значение по умолчанию (1 МБ). Большие значения
 *                      снижают число read(), но линейно повышают память.
 *
 * @return Агрегированная статистика (totalLines, headings, paragraphs,
 *         listItems, foreignLines). Если файл не открылся — все поля = 0
 *         и в stderr выводится сообщение.
 *
 * @note Функция не потокобезопасна при одновременной записи в один out
 *       из нескольких потоков.
 * @warning На 6-ГБ файле с большим числом элементов results.txt может
 *          занимать гигабайты — объём вывода ограничен только входом.
 */
AnalysisStats analyzeMarkdownFile(const std::string& filename,
                                  std::ostream& out,
                                  std::size_t blockSize = 1024 * 1024);