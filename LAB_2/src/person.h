#pragma once

#include <ostream>
#include <string>

/**
 * @brief Данные анкеты пользователя.
 *
 * @note Для полей birthDate/phone/email формат после нормализации:
 *       DD.MM.YYYY, +7XXXXXXXXXX, <local@domain>. До нормализации —
 *       произвольная строка, введённая пользователем или генератором.
 */
struct Person {
    std::string surname;     ///< Фамилия (кириллица или ASCII, UTF-8).
    std::string name;        ///< Имя.
    std::string patronymic;  ///< Отчество.
    std::string birthDate;   ///< Дата рождения: DD.MM.YYYY после нормализации.
    std::string phone;       ///< Телефон: +7XXXXXXXXXX после нормализации.
    std::string email;       ///< Email: <local@domain> в нижнем регистре.
};

/**
 * @brief Приводит одну часть ФИО к единому виду.
 *
 * Удаляет все символы, кроме букв и дефиса, первую букву каждого
 * «слова» делает заглавной, остальные — строчными. Корректно работает
 * с кириллицей в UTF-8.
 *
 * @param part Исходная часть ФИО ("ИваН", "петРОви1ч").
 * @return Нормализованная строка ("Иван", "Петрович") или пустая,
 *         если после фильтрации не осталось букв.
 *
 * @note Дефис сохраняется, регистр после него снова повышается
 *       ("Петров-Водкин").
 */
std::string normalizeNamePart(const std::string& part);

/**
 * @brief Приводит дату рождения к формату DD.MM.YYYY.
 *
 * Принимает разделители '-', '.', '/' и определяет порядок групп по
 * длине: если первая группа ≥ 4 цифр — это год (YYYY-MM-DD), иначе
 * DD/MM/YYYY. Диапазоны: год 1900–2100, месяц 1–12, день 1–31
 * (без проверки числа дней в месяце).
 *
 * @param input Строка с датой в произвольном формате.
 * @return Нормализованная дата DD.MM.YYYY или пустая строка,
 *         если распарсить не удалось.
 */
std::string normalizeBirthDate(const std::string& input);

/**
 * @brief Приводит телефон к формату +7XXXXXXXXXX.
 *
 * Извлекает все цифры, отбрасывает разделители (пробелы, дефисы,
 * скобки). Ведущая 8 заменяется на 7, 10-значный
 * номер получает 7 в начало.
 *
 * @param input Строка с телефоном в любом формате.
 * @return +7XXXXXXXXXX или пустая строка, если после извлечения цифр
 *         длина != 11 или первая цифра != 7.
 */
std::string normalizePhone(const std::string& input);

/**
 * @brief Приводит email к формату <local@domain> в нижнем регистре.
 *
 * Удаляет угловые скобки, если пользователь их ввёл, приводит строку
 * к нижнему регистру и проверяет простым regex, что есть @ и домен с TLD.
 *
 * @param input Строка с email, возможно в <...>.
 * @return <local@domain> или пустая строка при неудаче.
 */
std::string normalizeEmail(const std::string& input);

/**
 * @brief Запрашивает у пользователя все поля анкеты через std::getline.
 *
 * @return Структура с введёнными строками (могут быть некорректными).
 */
Person inputPerson();

/**
 * @brief Нормализует все поля «на месте» и проверяет их корректность.
 *
 * Вызывает соответствующие normalize* для каждого поля и записывает
 * результат обратно в p. Даже при неудаче нормализованные значения
 * остаются в p — это нужно для anketa.txt, чтобы было видно, какое
 * именно поле «сломалось» (стало пустым).
 *
 * @param p Анкета; при успехе — полностью нормализована.
 * @return true, если все шесть полей непустые после нормализации.
 *
 * @note Диагностические сообщения о конкретной ошибке выводятся в
 *       std::cerr; вызывающая сторона видит только true/false.
 */
bool validateAndNormalize(Person& p);

/**
 * @brief Выводит нормализованную анкету в std::cout одной строкой.
 *
 * @param p Анкета (обычно после нормализации).
 */
void printPerson(const Person& p);

/**
 * @brief Сохраняет анкету в поток в развёрнутом виде.
 *
 * Пишет три блока: исходные данные (raw), нормализованные (normalized)
 * и итоговую строку + статус.
 *
 * @param os Поток для записи; должен быть открыт заранее.
 * @param raw Исходные данные (до нормализации).
 * @param normalized Данные после validateAndNormalize.
 * @param valid Результат validateAndNormalize.
 *
 * @note Файл создаётся даже при valid == false.
 */
void writePerson(std::ostream& os,
                 const Person& raw,
                 const Person& normalized,
                 bool valid);